// Turns a model spec into a runnable NumPyro script. Site names equal node names,
// so the joint draws it writes back map onto the same worlds the person sees.
import { parseExpr, type Expr } from "./expr.ts";
import type { ModelNode, ModelSpec } from "./contracts.ts";
import { isDiscrete } from "./sim.ts";

const FN: Record<string, string> = {
  exp: "jnp.exp",
  log: "jnp.log",
  sqrt: "jnp.sqrt",
  abs: "jnp.abs",
  sin: "jnp.sin",
  cos: "jnp.cos",
  tanh: "jnp.tanh",
  logistic: "jax.nn.sigmoid",
  min: "jnp.minimum",
  max: "jnp.maximum",
  pow: "jnp.power",
};

function py(e: Expr, data: Set<string>): string {
  switch (e.type) {
    case "num":
      return String(e.value);
    case "var": {
      if (e.name === "pi" && !e.index) return "jnp.pi";
      const base = data.has(e.name) ? `d_${e.name}` : `v_${e.name}`;
      return e.index ? `${base}[d_${e.index}]` : base;
    }
    case "neg":
      return `(-${py(e.arg, data)})`;
    case "bin":
      return `(${py(e.left, data)} ${e.op === "^" ? "**" : e.op} ${py(e.right, data)})`;
    case "call":
      if (e.fn === "step") return `jnp.where(${py(e.args[0], data)} > 0, 1.0, 0.0)`;
      return `${FN[e.fn]}(${e.args.map((a) => py(a, data)).join(", ")})`;
  }
}

function distPy(n: ModelNode, data: Set<string>): string {
  const a = (k: string) => py(parseExpr(n.dist!.args[k]), data);
  switch (n.dist!.family) {
    case "normal":
      return `dist.Normal(${a("mu")}, ${a("sigma")})`;
    case "lognormal":
      return `dist.LogNormal(${a("mu")}, ${a("sigma")})`;
    case "halfnormal":
      return `dist.HalfNormal(${a("sigma")})`;
    case "exponential":
      return `dist.Exponential(${a("rate")})`;
    case "uniform":
      return `dist.Uniform(${a("lower")}, ${a("upper")})`;
    case "studentt":
      return `dist.StudentT(${a("nu")}, ${a("mu")}, ${a("sigma")})`;
    case "gamma":
      return `dist.Gamma(${a("shape")}, ${a("rate")})`;
    case "beta":
      return `dist.Beta(${a("a")}, ${a("b")})`;
    case "poisson":
      return `dist.Poisson(${a("rate")})`;
    case "bernoulli":
      return `dist.Bernoulli(probs=${a("p")})`;
    case "binomial":
      return `dist.Binomial(total_count=${a("n")}, probs=${a("p")})`;
  }
}

export function numpyroScript(spec: ModelSpec, versionId: string): { code: string; warnings: string[] } {
  const data = new Set(spec.data.map((d) => d.name));
  const warnings: string[] = [];
  const body: string[] = [];
  const indent = (lines: string[], plate: string | null) =>
    plate ? [`    with numpyro.plate("${plate}", sizes["${plate}"]):`, ...lines.map((l) => `    ${l}`)] : lines;

  for (const d of spec.data) {
    body.push(`    d_${d.name} = jnp.asarray(data["${d.name}"]${d.indexOf ? ", dtype=jnp.int32" : ""})`);
  }
  for (const n of spec.nodes) {
    if (n.role === "deterministic") {
      body.push(`    v_${n.name} = numpyro.deterministic("${n.name}", ${py(parseExpr(n.expr!), data)}${n.plate ? ` * jnp.ones(sizes["${n.plate}"])` : ""})`);
      continue;
    }
    if (n.role !== "observed") {
      if (isDiscrete(n)) warnings.push(`${n.name} は離散の潜在変数なので NUTS では扱えません。周辺化するか別の手法が必要です`);
      body.push(...indent([`    v_${n.name} = numpyro.sample("${n.name}", ${distPy(n, data)})`], n.plate));
      continue;
    }
    if (n.censorAbove) {
      // Right-censored at the recording limit: the likelihood of a capped record is P(value ≥ cap).
      body.push(
        `    y_${n.name} = jnp.asarray(data["${n.name}"])`,
        `    cap_${n.name} = ${py(parseExpr(n.censorAbove), data)} * jnp.ones_like(y_${n.name})`,
        `    with numpyro.plate("${n.plate ?? "_one"}", y_${n.name}.shape[0]):`,
        `        d_ = ${distPy(n, data)}`,
        `        cens = y_${n.name} >= cap_${n.name} - 1e-9`,
        // double where: the unused branch must not produce NaN gradients
        `        sf = jnp.where(cens, 1.0 - d_.cdf(cap_${n.name}), 1.0)`,
        `        log_sf = jnp.log(jnp.clip(sf, 1e-300, 1.0))`,
        `        numpyro.factor("${n.name}", jnp.where(cens, log_sf, d_.log_prob(y_${n.name})))`,
      );
    } else {
      body.push(...indent([`    numpyro.sample("${n.name}", ${distPy(n, data)}, obs=jnp.asarray(data["${n.name}"]))`], n.plate));
    }
  }

  const keep = spec.nodes.filter((n) => n.role === "param" || n.role === "latent").map((n) => n.name);
  // Plated normal latents are sampled non-centred: with few observations per element the
  // centred form is a funnel. Site names stay the same, so draws still map back.
  const reparam = spec.nodes
    .filter((n) => n.role === "latent" && n.plate && (n.dist?.family === "normal" || n.dist?.family === "studentt"))
    .map((n) => n.name);
  const code = `#!/usr/bin/env python3
# Generated by Possible Worlds from "${spec.title.replace(/"/g, "'")}" (version ${versionId}).
# Site names equal the model's node names. Edit freely, but keep them, so the draws map back.
#
#   uv run --with numpyro --with jax python <this file> dataset.json run.json [--draws 500 --warmup 500 --chains 4]
#
# Then attach run.json in Claude Code with worlds_attach_run.
import argparse
import json

import jax
import jax.numpy as jnp
import numpy as np
import numpyro
import numpyro.distributions as dist
from numpyro.diagnostics import summary
from numpyro.infer import MCMC, NUTS
from numpyro.infer.reparam import LocScaleReparam
from numpyro.handlers import reparam

numpyro.enable_x64()

VERSION_ID = "${versionId}"
KEEP = ${JSON.stringify(keep)}
NONCENTERED = ${JSON.stringify(reparam)}
${warnings.map((w) => `# WARNING: ${w}`).join("\n")}

def model(data, sizes):
${body.join("\n")}


def build(centered):
    if centered or not NONCENTERED:
        return model
    return reparam(model, config={k: LocScaleReparam(centered=0) for k in NONCENTERED})


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("dataset")
    ap.add_argument("out")
    ap.add_argument("--draws", type=int, default=500)
    ap.add_argument("--warmup", type=int, default=500)
    ap.add_argument("--chains", type=int, default=4)
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--keep", type=int, default=400, help="draws written back to the app")
    ap.add_argument("--target-accept", type=float, default=0.8, help="raise (e.g. 0.95) when there are divergences")
    ap.add_argument("--centered", action="store_true", help="sample plated latents in the centred form")
    args = ap.parse_args()
    numpyro.set_host_device_count(args.chains)

    with open(args.dataset, encoding="utf-8") as f:
        ds = json.load(f)
    data = {k: np.asarray(v, dtype=float) for k, v in ds["columns"].items()}
    sizes = ds["plates"]

    mcmc = MCMC(NUTS(build(args.centered), target_accept_prob=args.target_accept), num_warmup=args.warmup, num_samples=args.draws, num_chains=args.chains, progress_bar=False)
    mcmc.run(jax.random.PRNGKey(args.seed), data, sizes, extra_fields=("diverging",))

    by_chain = mcmc.get_samples(group_by_chain=True)
    diag = summary({k: by_chain[k] for k in KEEP})
    rhat = [float(np.nanmax(v["r_hat"])) for v in diag.values()]
    ess = [float(np.nanmin(v["n_eff"])) for v in diag.values()]
    divergences = int(np.asarray(mcmc.get_extra_fields()["diverging"]).sum())

    flat = mcmc.get_samples()
    total = next(iter(flat.values())).shape[0]
    pick = np.linspace(0, total - 1, min(args.keep, total)).round().astype(int)
    draws = {}
    for k in KEEP:
        v = np.asarray(flat[k])[pick]
        draws[k] = v.reshape(len(pick), -1).tolist()

    run = {
        "versionId": VERSION_ID,
        "datasetId": ds["id"],
        "method": f"NumPyro NUTS {args.chains}x{args.draws}{'' if args.centered or not NONCENTERED else ' non-centred'} accept {args.target_accept}",
        "note": "",
        "diagnostics": {"maxRhat": max(rhat), "minEss": min(ess), "divergences": divergences, "chains": args.chains},
        "draws": draws,
    }
    with open(args.out, "w", encoding="utf-8") as f:
        json.dump(run, f)
    print(json.dumps(run["diagnostics"]))


if __name__ == "__main__":
    main()
`;
  return { code, warnings };
}
